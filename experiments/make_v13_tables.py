"""Generate every v13 manuscript number and table from released records."""
from pathlib import Path
from fractions import Fraction
import json
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'tables'
METHODS=['MM','PL','CI_2pct','MR_CI_nominal_1pct']
LABELS={'MM':'MM','PL':'PL','CI_2pct':'CI-2\\%','MR_CI_nominal_1pct':'RB'}

def table(caption,label,header,rows,columns,wide=False):
    env='table*' if wide else 'table'
    return ('% Generated by experiments/make_v13_tables.py; do not edit.\n'
        f'\\begin{{{env}}}[tb]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n'
        +('\\scriptsize' if wide else '\\footnotesize')+'\\setlength{\\tabcolsep}{2.5pt}\n'
        f'\\begin{{tabular}}{{@{{}}{columns}@{{}}}}\n\\toprule\n'+header+r'\\'+'\n\\midrule\n'
        +'\n'.join(' & '.join(map(str,row))+r'\\' for row in rows)
        +'\n\\bottomrule\n\\end{tabular}\n'+f'\\end{{{env}}}\n')

def main():
    data={n:json.loads((ROOT/f'results/endpoint_regret_v13_n{n}.json').read_text()) for n in [7,8,9]}
    summaries={n:d['summary'] for n,d in data.items()}
    macros={}
    s=summaries[7]
    macros.update({'r13.settings':s['settings'],'r13.improved':s['MR_vs_CI']['material_R_wins_1e9'],
        'r13.changed':s['MR_vs_CI']['changed_plan'],'r13.tight':s['methods']['CI_2pct']['rectangular_tightening_settings'],
        'r13.tightmean':f"{s['methods']['CI_2pct']['mean']['rectangular_bound_tightening_pct']:.2f}",
        'r13.maxreduction':f"{s['MR_vs_CI']['max_relative_R_improvement_pct']:.2f}",
        'r13.maxn':max(data),'r13.pairs':s['primitive_pair_oracle_evaluations'],
        'r13.flows':s['integer_maxflow_calls'],'r13.candidates':s['total_dual_budget_candidates'],
        'r13.seconds':f"{s['case_processing_seconds']:.2f}"})
    for label,method in [('MR','MR_CI_nominal_1pct'),('CI','CI_2pct'),('PL','PL')]:
        macros[f'r13.{label}.neutral']=f"{s['methods'][method]['mean']['neutral_mean_regret_pct']:.2f}"
    rows=[]
    for method in METHODS:
        a=s['methods'][method]
        rows.append([LABELS[method],f"{a['mean']['worst_regret']:.5f}",
            f"{a['mean']['rectangular_regret_upper']:.5f}",f"{a['mean']['smooth_mean_regret_pct']:.2f}",
            f"{a['mean']['neutral_mean_regret_pct']:.2f}",f"{a['maximum']['robust_excess_pct']:.2f}"])
    caption=(r'Exact common-membership certificates on all 96 seven-stop settings: eight inputs, two OWA profiles, '
        r'two policies and three $\alpha$. $R$ and $B_{\rm sep}=J^+-\min J^-$ are means in absolute normalized '
        r'objective units; smooth/neutral columns are relative regrets (\%) on constructed completions. '
        r'Cost: largest relative excess of $J^+$ over MM (\%). RB retains the 2\% cost budget and allows '
        r'at most 1\% extra PL score relative to CI. These are different quantities; no calibrated expected cost is asserted.')
    (OUT/'tab_regret_v13.tex').write_text(table(caption,'tab:regret-v13',
        r'Method & $R$ & $B_{\rm sep}$ & Smooth & Neutral & Cost',rows,'lrrrrr'))
    rows=[]
    for n,a in summaries.items():
        for key,value in [('plans',a['full_enumerated_plans_per_case']),('eligiblemax',a['eligible_domain_max']),
            ('wins',a['MR_vs_CI']['material_R_wins_1e9']),('exactwins',a['MR_vs_CI']['strict_R_wins']),
            ('settings',a['settings'])]:
            macros[f'r13.n{n}.{key}']=str(value).replace(',',r'\,') if not isinstance(value,int) else f'{value:,}'.replace(',',r'\,')
        rows.append([n,f"{a['full_enumerated_plans_per_case']:,}".replace(',',r'\,'),
            f"{a['eligible_domain_max']:,}".replace(',',r'\,'),a['MR_vs_CI']['material_R_wins_1e9'],
            f"{a['case_processing_seconds']:.2f}"])
    caption=(r'Complete-domain results, 96 settings at each size. Plans: all directed-route partitions per input '
        r'before feasibility filtering; eligible: largest competitor domain. Wins: RB reduces CI absolute $R$ '
        r'by more than $10^{-9}$. At nine tasks there are 43 exact rational wins, including eight smaller numerical '
        r'differences. Time is the sum of per-input wall times including enumeration and evaluation completions, '
        r'not an operational routing benchmark. No regret or budget losses occur. All eight inputs are retained at each size.')
    (OUT/'tab_regret_scaling_v13.tex').write_text(table(caption,'tab:regret-scaling-v13',
        r'$n$ & Plans & Eligible & Wins & Time (s)',rows,'rrrrr'))
    alltex=[]
    for n,payload in data.items():
        raw=[r for c in payload['raw'] for r in c['records']]
        rows=[]
        for profile in ['arithmetic','top_heavy']:
            for policy in ['uncapped','capped']:
                for method in METHODS:
                    vals=[next(m for m in r['methods'] if m['method']==method) for r in raw
                          if r['profile']==profile and r['policy']==policy]
                    avg=lambda key:float(np.mean([v[key] for v in vals]))
                    mx=lambda key:max(v[key] for v in vals)
                    rows.append(['Arith.' if profile=='arithmetic' else 'Top',
                        'free' if policy=='uncapped' else 'cap',LABELS[method],
                        f"{avg('worst_regret'):.5f}",f"{avg('rectangular_regret_upper'):.5f}",
                        f"{avg('smooth_mean_regret_pct'):.2f}",f"{avg('neutral_mean_regret_pct'):.2f}",
                        f"{mx('robust_excess_pct'):.2f}",f"{mx('nominal_excess_vs_CI_pct'):.2f}"])
        caption=(f'Complete results at {n} tasks, each row averaging eight inputs and three '+r'$\alpha$. '
            r'$R$ and $B_{\rm sep}$ are absolute normalized objective units; smooth/neutral are relative '
            r'test-regret means (\%). Cost: largest $J^+$ excess over MM (\%). Nominal: largest PL-score '
            r'excess over CI (\%). RB has 2\% cost and 1\% CI-relative nominal budgets. '
            r'All methods and oracle optima use the same policy-specific competitor domain. Negative nominal '
            r'excess for PL is allowed. Constructed-completion averages are not operational expectations.')
        alltex.append(table(caption,'tab:regret-all-v13' if n==7 else f'tab:regret-all-v13-n{n}',
            r'Weights & Policy & Method & $R$ & $B_{\rm sep}$ & Smooth & Neutral & Cost & Nominal',
            rows,'lllrrrrrr',True))
    (OUT/'tab_regret_all_v13.tex').write_text('\n'.join(alltex))
    tex='% Generated by experiments/make_v13_tables.py; do not edit.\n'
    tex+=''.join('\\expandafter\\def\\csname res@'+key+'\\endcsname{'+str(value)+'}\n' for key,value in sorted(macros.items()))
    (OUT/'numbers_v13.tex').write_text(tex)
    print(json.dumps({'tables':3,'macro_file':'numbers_v13.tex','macros':len(macros),'sizes':list(data)}))

if __name__=='__main__':main()
