"""Generate the release-12 tables, figure coordinates and macros.

Inputs: results/endpoint_certified_v12.json and results/reliability20_strata_v12.json.
Outputs (tables/ and, when present, Main/tables and Supplement/tables):
numbers_v12.tex, tab_endpoint_certified_v12.tex, fig_frontier_v12.tex,
tab_endpoint_certified_all_v12.tex, tab_reliability20_strata_v12.tex.
"""
from __future__ import annotations

from pathlib import Path
import json
import statistics as st

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT.parents[1]
T = ROOT/'tables'
LABELS = {'triangular': 'Tri.', 'sweep': 'Sweep', 'minimax': 'MM', 'ci_0': 'CI-0',
          'ci_0.01': 'CI-1\\%', 'ci_0.02': 'CI-2\\%', 'ci_0.05': 'CI-5\\%', 'ci_0.1': 'CI-10\\%',
          'piecewise_linear': 'PL'}
MAIN_METHODS = ('triangular', 'sweep', 'minimax', 'ci_0.02', 'ci_0.05', 'piecewise_linear')


class Writer:
    """Write a generated file to the archive and to the manuscript folders."""

    def __init__(self, destinations):
        self.destinations = destinations

    def write(self, name, text):
        T.mkdir(exist_ok=True)
        (T/name).write_text(text)
        for dest in self.destinations:
            folder = PROJECT/dest/'tables'
            if folder.is_dir():
                (folder/name).write_text(text)


class TableFormatter:
    @staticmethod
    def table(caption, label, head, rows, spec, wide=False, size='\\footnotesize', sep='2.5pt'):
        env = 'table*' if wide else 'table'
        return ('% Generated by experiments/make_v12_tables.py; do not edit.\n'
                '\\begin{'+env+'}[tb]\n\\centering\n\\caption{'+caption+'}\n\\label{'+label+'}\n'
                + size+'\\setlength{\\tabcolsep}{'+sep+'}\n\\begin{tabular}{@{}'+spec+'@{}}\n'
                '\\toprule\n'+head+'\\\\\\midrule\n'
                + '\n'.join(' & '.join(map(str, r))+'\\\\' for r in rows)
                + '\n\\bottomrule\n\\end{tabular}\n\\end{'+env+'}\n')


class CertifiedSummary:
    """Aggregate the certified-interpolation records."""

    def __init__(self, payload):
        self.rows = [dict(r, id=c['id']) for c in payload['raw'] for r in c['records']]
        self.protocol = payload['protocol']

    def select(self, **kw):
        return [r for r in self.rows if all(r[k] == v for k, v in kw.items())]

    @staticmethod
    def stats(rows):
        rg = np.array([r['robust_gap_pct'] for r in rows])
        sm = np.array([x for r in rows for x in r['smooth_regret_pct']])
        ne = np.array([x for r in rows for x in r['neutral_regret_pct']])
        s01 = np.array([r['stress_regret_pct'][0] for r in rows])
        s10 = np.array([r['stress_regret_pct'][1] for r in rows])
        return dict(settings=len(rows), robust_mean=rg.mean(), robust_max=rg.max(),
                    smooth_mean=sm.mean(), smooth_max=sm.max(),
                    neutral_mean=ne.mean(), neutral_median=float(np.median(ne)),
                    neutral_p90=float(np.percentile(ne, 90)), neutral_max=ne.max(),
                    stress01_mean=s01.mean(), stress10_mean=s10.mean(), neutral_n=len(ne))

    def aggregate(self):
        out = {}
        for grid in ('two', 'four'):
            for policy in ('uncapped', 'capped'):
                for m in LABELS:
                    out[f'{grid}.{policy}.{m}'] = self.stats(self.select(grid=grid, policy=policy, method=m))
        return out

    def paired(self, a, b, grid='four', family='neutral'):
        """Settings of one grid in which method a has a mean regret not above method b,
        and settings in which both methods select the same plan."""
        key = family+'_regret_pct'
        index = {}
        for r in self.rows:
            if r['grid'] == grid:
                index[(r['id'], r['profile'], r['policy'], r['alpha'], r['method'])] = (st.mean(r[key]), r['plan_index'])
        settings = {k[:4] for k in index}
        wins = sum(index[s+(a,)][0] <= index[s+(b,)][0]+1e-9 for s in settings)
        same = sum(index[s+(a,)][1] == index[s+(b,)][1] for s in settings)
        return wins, same, len(settings)


class StrataSummary:
    def __init__(self, payload):
        self.groups = payload['groups']


def fmt(x, d=2):
    return f'{x:.{d}f}'


def main():
    writer = Writer(('Main', 'Supplement'))
    cert = CertifiedSummary(json.loads((ROOT/'results/endpoint_certified_v12.json').read_text()))
    agg = cert.aggregate()
    # ---------------- main table
    rows = []
    for policy in ('uncapped', 'capped'):
        for m in MAIN_METHODS:
            v = agg[f'four.{policy}.{m}']
            rows.append(['free' if policy == 'uncapped' else 'cap', LABELS[m], fmt(v['robust_mean']),
                         fmt(v['robust_max'], 1), fmt(v['smooth_mean']), fmt(v['neutral_mean']),
                         fmt(v['neutral_p90'], 1), fmt(v['stress01_mean']), fmt(v['stress10_mean'])])
    caption = ('Certified interpolation on the exhaustive seven-stop domains of eight directed Amazon inputs '
               '(four-level grid; free/cap: no extra constraint/common worst-cell ceiling $0.30$). '
               'CI-$\\tau$ minimizes the PL objective subject to $J^+\\le(1+\\tau)\\min J^+$ '
               '(Corollary~\\ref{cor:certified}). Robust: relative excess of $J^+$ over MM (mean/max., \\%). '
               'Regret: relative excess over the exact test optimum on the same feasible set (\\%), '
               'on the original smooth completions (mean), on 30 neutral random admissible completions per input '
               '(mean/90th percentile) and on the stress powers $p=0.1$ and $p=10$ (mean). '
               'Each row covers eight inputs, three $\\alpha$ and two OWA profiles; repetitions are descriptive.')
    head = ('Pol. & Method & \\multicolumn{2}{c}{Robust} & Smooth & \\multicolumn{2}{c}{Neutral} & $p{=}0.1$ & $p{=}10$\\\\'
            '\\cmidrule(lr){3-4}\\cmidrule(lr){6-7}\n & & mean & max. & mean & mean & P90 & mean & mean')
    writer.write('tab_endpoint_certified_v12.tex',
                 TableFormatter.table(caption, 'tab:endpoint-certified-v12', head, rows, 'llrrrrrrr', sep='2.2pt'))
    # ---------------- supplementary table
    rows = []
    for grid in ('two', 'four'):
        for policy in ('uncapped', 'capped'):
            for m in LABELS:
                v = agg[f'{grid}.{policy}.{m}']
                rows.append([('2' if grid == 'two' else '4')+('/cap' if policy == 'capped' else '/free'), LABELS[m],
                             fmt(v['robust_mean']), fmt(v['robust_max']), fmt(v['smooth_mean']), fmt(v['smooth_max'], 1),
                             fmt(v['neutral_mean']), fmt(v['neutral_median']), fmt(v['neutral_p90']),
                             fmt(v['neutral_max'], 1), fmt(v['stress01_mean']), fmt(v['stress10_mean'])])
    caption = ('Certified interpolation, all tolerances, grids and policies. CI-0 is minimax with a PL tie-break. '
               'Neutral completions draw, for every leg and every interval between adjacent fine-grid endpoints, '
               'an independent exponent log-uniform on $[0.1,10]$; 30 draws per input, fixed seed. '
               'All entries are percentages; Robust is the relative excess of $J^+$ over the minimax value, '
               'regret the relative excess over the exact optimum of the same completion on the same feasible set.')
    head = ('Grid/pol. & Method & \\multicolumn{2}{c}{Robust} & \\multicolumn{2}{c}{Smooth} & '
            '\\multicolumn{4}{c}{Neutral} & $p{=}0.1$ & $p{=}10$\\\\'
            '\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-10}\n'
            ' & & mean & max. & mean & max. & mean & med. & P90 & max. & mean & mean')
    writer.write('tab_endpoint_certified_all_v12.tex',
                 TableFormatter.table(caption, 'tab:endpoint-certified-all-v12', head, rows, 'llrrrrrrrrrr', wide=True, sep='4pt'))
    # ---------------- frontier figure coordinates (four-level grid)
    path = ('minimax', 'ci_0.01', 'ci_0.02', 'ci_0.05', 'ci_0.1', 'piecewise_linear')
    lines = ['% Generated by experiments/make_v12_tables.py; do not edit.',
             '\\begin{tikzpicture}',
             '\\begin{axis}[width=0.98\\columnwidth,height=0.56\\columnwidth,xmin=-0.8,xmax=20,ymin=0,ymax=5.9,',
             '  xlabel={Largest robust gap over MM (\\%)},ylabel={Mean regret (\\%)},',
             '  legend style={font=\\scriptsize,at={(0.98,0.98)},anchor=north east},legend cell align=left,',
             '  tick label style={font=\\scriptsize},label style={font=\\small}]']
    for fam, style, name in (('neutral', 'pctblue,thick,mark=*', 'Neutral'), ('smooth', 'riskred,thick,dashed,mark=o', 'Smooth')):
        for policy, extra, pname in (('uncapped', '', 'free'),):
            pts = ' '.join(f'({agg[f"four.{policy}.{m}"]["robust_max"]:.3f},{agg[f"four.{policy}.{m}"][fam+"_mean"]:.3f})'
                           for m in path)
            lines.append(f'\\addplot[{style}] coordinates {{{pts}}};')
            lines.append(f'\\addlegendentry{{{name} completions}}')
    sw = agg['four.uncapped.sweep']
    lines.append(f'\\addplot[only marks,mark=triangle*,black,mark size=2.2pt] coordinates {{({sw["robust_max"]:.3f},{sw["neutral_mean"]:.3f})}};')
    lines.append('\\addlegendentry{Sweep (neutral)}')
    mm, pl = agg['four.uncapped.minimax'], agg['four.uncapped.piecewise_linear']
    lines.append(f'\\node[font=\\scriptsize,anchor=south west] at (axis cs:0.1,{mm["neutral_mean"]:.3f}) {{MM}};')
    lines.append(f'\\node[font=\\scriptsize,anchor=south east] at (axis cs:{pl["robust_max"]:.3f},{pl["neutral_mean"]:.3f}) {{PL}};')
    c2 = agg['four.uncapped.ci_0.02']
    lines.append(f'\\node[font=\\scriptsize,anchor=south west] at (axis cs:{c2["robust_max"]:.3f},{c2["neutral_mean"]:.3f}) {{CI-2\\%}};')
    lines += ['\\end{axis}', '\\end{tikzpicture}']
    writer.write('fig_frontier_v12.tex', '\n'.join(lines)+'\n')
    # ---------------- strata
    strata = json.loads((ROOT/'results/reliability20_strata_v12.json').read_text())['groups']
    names = {'all': 'All', 'operations': 'Operations', 'research_other': 'Research/other',
             'experience_2plus': 'Experience $\\ge2$ y', 'experience_below_2': 'Experience $<2$ y'}
    srows = []
    for g, lab in names.items():
        v = strata[g]
        icc = []
        for s in ('s1', 's2', 's3', 's4'):
            a = v['agreement'][s]
            icc.append(f'{a["icc_A1"]:.2f} [{a["icc_bootstrap_95"][0]:.2f}, {a["icc_bootstrap_95"][1]:.2f}]')
        srows.append([lab, v['n'], f'{v["departures"]["q030"]["exceed"]}/{v["departures"]["q030"]["judgments"]}',
                      f'{v["departures"]["q010"]["exceed"]}/{v["departures"]["q010"]["judgments"]}'] + icc)
    caption = ('Twenty-expert results by declared area and experience band. $E_{030}$, $E_{010}$: first-session '
               'judgments whose straight-branch residual exceeds the whole-minute rounding tolerance. '
               'ICC: test--retest ICC(A,1) of $q_{060}$ with paired-expert bootstrap 95\\% interval, per scenario. '
               'Strata of 4--13 respondents; descriptive, no group-difference test.')
    head = 'Stratum & $n$ & $E_{030}$ & $E_{010}$ & ICC S1 & ICC S2 & ICC S3 & ICC S4'
    writer.write('tab_reliability20_strata_v12.tex',
                 TableFormatter.table(caption, 'tab:reliability20-strata-v12', head, srows, 'lrrrllll', wide=True, sep='4pt'))
    # ---------------- macros
    macros = {}
    for key, v in agg.items():
        for metric in ('robust_mean', 'robust_max', 'smooth_mean', 'smooth_max', 'neutral_mean',
                       'neutral_median', 'neutral_p90', 'neutral_max', 'stress01_mean', 'stress10_mean'):
            macros[f'ci.{key}.{metric}'] = fmt(v[metric])
    base, c2, c5, pl = (agg[f'four.uncapped.{m}'] for m in ('minimax', 'ci_0.02', 'ci_0.05', 'piecewise_linear'))
    macros['ci.tau2.neutral.reduction'] = f'{100*(1-c2["neutral_mean"]/base["neutral_mean"]):.0f}'
    macros['ci.tau2.smooth.reduction'] = f'{100*(1-c2["smooth_mean"]/base["smooth_mean"]):.0f}'
    macros['ci.tau2.neutral.gapclosed'] = f'{100*(base["neutral_mean"]-c2["neutral_mean"])/(base["neutral_mean"]-pl["neutral_mean"]):.0f}'
    macros['ci.tau2.smooth.gapclosed'] = f'{100*(base["smooth_mean"]-c2["smooth_mean"])/(base["smooth_mean"]-pl["smooth_mean"]):.0f}'
    w, same, n = cert.paired('ci_0.02', 'minimax')
    macros['ci.tau2.wins.mm'], macros['ci.tau2.same.mm'], macros['ci.settings.four'] = w, same, n
    w, same, n = cert.paired('ci_0.02', 'piecewise_linear')
    macros['ci.tau2.wins.pl'], macros['ci.tau2.same.pl'] = w, same
    w, same, n = cert.paired('ci_0', 'minimax')
    macros['ci.tau0.same.mm'], macros['ci.tau0.changed.mm'] = same, n-same
    w, same, n = cert.paired('piecewise_linear', 'minimax')
    macros['pl.wins.mm'] = w
    macros['ci.draws'] = cert.protocol['neutral_draws']
    macros['ci.neutral.evaluations'] = sum(len(r['neutral_regret_pct']) for r in cert.rows)
    macros['ci.decisions'] = len(cert.rows)
    for g, v in strata.items():
        macros[f'strata.{g}.n'] = v['n']
        for lab in ('q030', 'q010'):
            macros[f'strata.{g}.{lab}.exceed'] = v['departures'][lab]['exceed']
            macros[f'strata.{g}.{lab}.n'] = v['departures'][lab]['judgments']
        for s in ('s1', 's2', 's3', 's4'):
            a = v['agreement'][s]
            macros[f'strata.{g}.{s}.icc'] = f'{a["icc_A1"]:.3f}'
            macros[f'strata.{g}.{s}.icc.low'] = f'{a["icc_bootstrap_95"][0]:.3f}'
            macros[f'strata.{g}.{s}.icc.high'] = f'{a["icc_bootstrap_95"][1]:.3f}'
    tex = ('% Generated by experiments/make_v12_tables.py; do not edit.\n\\makeatletter\n'
           '\\providecommand{\\res}[1]{\\@ifundefined{res@#1}{\\textbf{??}}{\\csname res@#1\\endcsname}}\n\\makeatother\n'
           + ''.join('\\expandafter\\def\\csname res@'+k+'\\endcsname{'+str(v)+'}\n' for k, v in macros.items()))
    writer.write('numbers_v12.tex', tex)
    summary = dict(aggregate=agg, macros=macros)
    (ROOT/'results/endpoint_certified_v12_summary.json').write_text(json.dumps(summary, indent=1)+'\n')
    for k in macros:
        if not k.startswith(('ci.two', 'ci.four', 'strata')):
            print(k, macros[k])


if __name__ == '__main__':
    main()
