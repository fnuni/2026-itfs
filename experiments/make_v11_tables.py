"""Generate compact and detailed tables from the v11 decision records."""
from pathlib import Path
import json, statistics as st
ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT.parents[1]
T = ROOT/'tables'


def table(name, caption, label, head, rows, spec, destination):
    environment = 'table*' if destination == 'Supplement' else 'table'
    spacing = '4pt' if destination == 'Supplement' else '2.5pt'
    tex = ('% Generated by experiments/make_v11_tables.py; do not edit.\n'
        '\\begin{'+environment+'}[tb]\n\\centering\n\\caption{'+caption+'}\n\\label{'+label+'}\n'
        '\\footnotesize\\setlength{\\tabcolsep}{'+spacing+'}\n\\begin{tabular}{@{}'+spec+'@{}}\n'
        '\\toprule\n'+head+'\\\\\\midrule\n'
        +'\n'.join(' & '.join(map(str, row))+'\\\\' for row in rows)
        +'\n\\bottomrule\n\\end{tabular}\n\\end{'+environment+'}\n')
    (T/name).write_text(tex)
    mirror = PROJECT/destination/'tables'
    if mirror.is_dir():
        (mirror/name).write_text(tex)


def summary(records):
    valid = [r for r in records if r['status'] == 'Optimal']
    tests = [t for r in valid for t in r['tests']]
    if not valid:
        return dict(valid=0, total=len(records))
    return dict(valid=len(valid), total=len(records),
        mean_gap_pct=st.mean(r['upper_gap_pct'] for r in valid),
        max_gap_pct=max(r['upper_gap_pct'] for r in valid),
        positive_gaps=sum(r['upper_gap'] > 1e-8 for r in valid),
        mean_regret_pct=st.mean(t['regret_pct'] for t in tests),
        max_regret_pct=max(t['regret_pct'] for t in tests),
        mean_regret=st.mean(t['regret'] for t in tests),
        max_regret=max(t['regret'] for t in tests),
        mean_upper_worst=st.mean(r['upper_max'] for r in valid),
        mean_test_worst=st.mean(t['worst_risk'] for t in tests),
        max_test_worst=max(t['worst_risk'] for t in tests),
        mean_owa_width=st.mean(r['upper_owa']-r['lower_owa'] for r in valid))


def main():
    T.mkdir(exist_ok=True)
    payload = json.loads((ROOT/'results/endpoint_information_v11.json').read_text())
    rr = [dict(r, id=case['id']) for case in payload['raw'] for r in case['records']]
    results, rows = {}, []
    labels = {'triangular': 'Tri.', 'minimax': 'MM', 'sweep': 'Sweep', 'piecewise_linear': 'PL'}
    for grid in ('two', 'four'):
        for policy in ('uncapped', 'capped'):
            for method in labels:
                key = '.'.join((grid, policy, method))
                v = summary([r for r in rr if r['grid']==grid and r['policy']==policy and r['method']==method])
                results[key] = v
                rows.append([('2' if grid=='two' else '4')+('/cap' if policy=='capped' else '/free'), labels[method],
                    f'{v["mean_gap_pct"]:.2f}', f'{v["mean_regret_pct"]:.2f}', f'{v["max_regret_pct"]:.1f}',
                    f'{v["mean_upper_worst"]:.3f}', f'{v["mean_test_worst"]:.3f}'])
    table('tab_endpoint_decision_v11.tex',
        'Exhaustive seven-stop restrictions of eight directed Amazon inputs, with constructed heterogeneous endpoints. Two/four interior endpoints share support and mode; free/cap means no extra constraint/a common certified worst-cell ceiling $0.30$. PL linearly interpolates the same endpoints available to MM and Sweep; Tri. uses support and mode. Each row averages eight route means over three $\\alpha$, two OWA profiles and three original smooth completions. Gap: mean relative upper-objective excess over MM (\\%); regret: relative excess over the exact test optimum on the same feasible set (mean/max., \\%); $M^+$/$M$: mean certified/test worst-cell risk. The upper objective also equals the grid-specific common-adversary objective, a deterministic certificate. All capped domains are feasible; repetitions are descriptive.',
        'tab:endpoint-decision-v11', 'Grid/policy & Method & Gap & Regret & Max. & $M^+$ & $M$', rows, 'llrrrrr', 'Main')
    detail = []
    for profile in ('arithmetic', 'top_heavy'):
        for grid in ('two', 'four'):
            for policy in ('uncapped', 'capped'):
                for method in labels:
                    v = summary([r for r in rr if r['profile']==profile and r['grid']==grid and r['policy']==policy and r['method']==method])
                    detail.append([f'{.5 if profile=="arithmetic" else .7:.1f}', 2 if grid=='two' else 4,
                        'cap' if policy=='capped' else 'free', labels[method], f'{v["valid"]}/{v["total"]}',
                        f'{v["mean_gap_pct"]:.3f}', f'{v["mean_regret_pct"]:.2f}',
                        f'{v["max_regret_pct"]:.1f}', f'{v["mean_upper_worst"]:.3f}',f'{v["mean_test_worst"]:.3f}'])
    table('tab_endpoint_weights_v11.tex',
        'Weight sensitivity on the same exhaustive domains: arithmetic weights $(0.5,1/3,1/6)$ and top-heavy weights $(0.7,0.2,0.1)$. PL uses the same endpoint information as MM and Sweep. Each row has eight routes and three preferences; original smooth-completion regrets use the exact oracle with the same policy feasible set. Gap and regret are percentages. Repeated settings are not independent observations.',
        'tab:endpoint-weights-v11', '$w_1$ & Grid & Policy & Method & Feas. & Gap & Regret & Max. & $M^+$ & $M$',
        detail, 'rlllrrrrrr', 'Supplement')
    perroute = []
    for case in payload['raw']:
        for grid in ('two','four'):
            v = {m: summary([r for r in case['records'] if r['grid']==grid and r['policy']=='uncapped' and r['method']==m])
                 for m in labels}
            perroute.append([case['id'], 2 if grid=='two' else 4, case['modal_feasible_plans'],
                f'{case["L"]:.2f}', f'{v["triangular"]["mean_regret_pct"]:.2f}',
                f'{v["minimax"]["mean_regret_pct"]:.2f}',f'{v["sweep"]["mean_regret_pct"]:.2f}',
                f'{v["piecewise_linear"]["mean_regret_pct"]:.2f}',
                f'{v["sweep"]["max_gap_pct"]:.2f}'])
    table('tab_endpoint_routes_v11.tex',
        'Per-route results on the fixed modal-feasible domain. $L=1.2$ times the exact modal bottleneck, in minutes. Regrets (\\%) average three preferences, two weights and the three original smooth completions within each route; last column is the largest robust-objective gap (\\%) of the exact sweep. Every route has 32,760 candidate plans before the modal filter, and all 13,699 nonempty directed tours are considered.',
        'tab:endpoint-routes-v11', 'Route & Grid & Plans & $L$ & Tri. regret & MM regret & Sweep regret & PL regret & Sweep max.',
        perroute, 'lrrrrrrrr', 'Supplement')
    stress_results, stress_rows = {}, []
    powers = payload['protocol']['extension']['stress_powers']
    for grid in ('two', 'four'):
        for policy in ('uncapped', 'capped'):
            for method in labels:
                values = []
                for power in powers:
                    selected = [r for r in rr if r['grid']==grid and r['policy']==policy and r['method']==method]
                    tests = [t for r in selected for t in r['stress_tests'] if t['power']==power]
                    v = dict(mean_regret_pct=st.mean(t['regret_pct'] for t in tests),
                        max_regret_pct=max(t['regret_pct'] for t in tests),
                        mean_test_worst=st.mean(t['worst_risk'] for t in tests),
                        max_test_worst=max(t['worst_risk'] for t in tests), tests=len(tests))
                    stress_results[f'{power:g}.{grid}.{policy}.{method}'] = v
                    values.extend([f'{v["mean_regret_pct"]:.2f}', f'{v["max_regret_pct"]:.2f}'])
                stress_rows.append([('2' if grid=='two' else '4')+('/cap' if policy=='capped' else '/free'), labels[method]]+values)
    table('tab_endpoint_stress_v11.tex',
        'Fixed additional stress completions on the same exhaustive domains and selected decisions. Powers $0.1$ and $10$ are reciprocal, symmetric on a log scale; they were fixed before these additional evaluations, after inspection of the original experiment, without tuning. This is not preregistration. Every completion preserves the full fine-grid endpoints. Mean/max. relative regrets (\\%) use the exact oracle for the identical completion, weights, preference and policy feasible set. These two stresses are reported separately from the original smooth family; neither family is a distribution of operational uncertainty. The common least-favourable completion is instead the upper objective reported in Table~\\ref{tab:endpoint-decision-v11}.',
        'tab:endpoint-stress-v11', 'Grid/policy & Method & $p=0.1$ mean & Max. & $p=10$ mean & Max.',
        stress_rows, 'llrrrr', 'Supplement')
    index = {(r['id'],r['grid'],r['profile'],r['policy'],r['alpha'],r['method']):r for r in rr}
    value_info, caps = [], []
    for r in rr:
        if r['method']!='minimax' or r['status']!='Optimal':
            continue
        if r['grid']=='two':
            fine=index[(r['id'],'four',r['profile'],r['policy'],r['alpha'],r['method'])]
            value_info.append(dict(id=r['id'], profile=r['profile'], policy=r['policy'], alpha=r['alpha'],
                upper_improvement=r['upper_J']-fine['upper_J'],
                mean_test_regret_change=st.mean(t['regret'] for t in fine['tests'])-st.mean(t['regret'] for t in r['tests']),
                selected_plan_changed=r['plan_index']!=fine['plan_index']))
        if r['policy']=='capped':
            unc=index[(r['id'],r['grid'],r['profile'],'uncapped',r['alpha'],r['method'])]
            caps.append(dict(id=r['id'],grid=r['grid'],profile=r['profile'],alpha=r['alpha'],
                upper_cost_pct=100*(r['upper_J']/unc['upper_J']-1),
                workload_cost_pct=100*(r['workload']/unc['workload']-1),
                uncapped_upper_max=unc['upper_max'], capped_upper_max=r['upper_max']))
    out=dict(protocol=payload['protocol'], aggregate=results, stress_aggregate=stress_results, grid_changes=value_info, cap_costs=caps,
        counts=dict(routes=len(payload['raw']), records=len(rr), test_evaluations=sum(len(r.get('tests',[])) for r in rr),
                    stress_evaluations=sum(len(r.get('stress_tests',[])) for r in rr),
                    original_decisions=sum(r['anchored_original_decision'] for r in rr),
                    plans=sum(c['modal_feasible_plans'] for c in payload['raw'])))
    (ROOT/'results/endpoint_information_v11_summary.json').write_text(json.dumps(out, indent=2)+'\n')
    macros={'ed.routes':len(payload['raw']), 'ed.plans':out['counts']['plans'],
        'ed.decisions':len(rr), 'ed.tests':out['counts']['test_evaluations'],
        'ed.stress.tests':out['counts']['stress_evaluations'],
        'ed.original.decisions':out['counts']['original_decisions'],
        'info.smooth.powers':','.join(f'{p:g}' for p in payload['protocol']['extension']['smooth_powers']),
        'info.stress.powers':','.join(f'{p:g}' for p in powers),
        'ed.grid.changed':sum(v['selected_plan_changed'] for v in value_info),
        'ed.grid.cases':len(value_info),
        'ed.grid.regret.better':sum(v['mean_test_regret_change'] < -1e-9 for v in value_info),
        'ed.grid.regret.worse':sum(v['mean_test_regret_change'] > 1e-9 for v in value_info),
        'ed.cap.binds':sum(c['uncapped_upper_max'] > .30+1e-9 for c in caps),
        'ed.cap.cases':len(caps),
        'ed.cap.cost.max':f'{max(c["upper_cost_pct"] for c in caps):.2f}',
        'ed.cap.cost.mean':f'{st.mean(c["upper_cost_pct"] for c in caps):.2f}',
        'ed.cap.workload.max':f'{max(c["workload_cost_pct"] for c in caps):.2f}'}
    for policy in ('uncapped','capped'):
        selected = [v for v in value_info if v['policy']==policy]
        macros[f'ed.grid.{policy}.changed'] = sum(v['selected_plan_changed'] for v in selected)
        macros[f'ed.grid.{policy}.cases'] = len(selected)
    top_heavy = [r for r in rr if r['method']=='sweep' and r['profile']=='top_heavy']
    macros['ed.sweep.top_heavy.losses'] = sum(r['upper_gap']>1e-8 for r in top_heavy)
    macros['ed.sweep.top_heavy.cases'] = len(top_heavy)
    pl_summaries = [v for k,v in results.items() if k.endswith('.piecewise_linear')]
    macros['ed.pl.robust.mean.min'] = f'{min(v["mean_gap_pct"] for v in pl_summaries):.3f}'
    macros['ed.pl.robust.mean.max'] = f'{max(v["mean_gap_pct"] for v in pl_summaries):.3f}'
    macros['ed.pl.robust.max'] = f'{max(v["max_gap_pct"] for v in pl_summaries):.3f}'
    for key, value in stress_results.items():
        for metric,v in value.items():
            macros[f'ed.stress.{key}.{metric}'] = str(v) if isinstance(v,int) else f'{v:.3f}'
    for key,v in results.items():
        for metric in ('mean_gap_pct','max_gap_pct','positive_gaps','mean_regret_pct','max_regret_pct',
                       'mean_upper_worst','mean_test_worst','mean_owa_width'):
            value=v[metric]
            macros['ed.'+key+'.'+metric]=str(value) if isinstance(value,int) else f'{value:.3f}'
    tex='% Generated by make_v11_tables.py\n'+''.join('\\expandafter\\def\\csname res@'+k+'\\endcsname{'+str(v)+'}\n' for k,v in macros.items())
    for dest in (T,PROJECT/'Main/tables',PROJECT/'Supplement/tables'):
        if dest.is_dir():
            (dest/'numbers_endpoint_decision_v11.tex').write_text(tex)
    print(json.dumps({k:out[k] for k in ('counts','aggregate')},indent=2))


if __name__=='__main__':
    main()
