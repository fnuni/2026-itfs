def ablation_table():
    if not exists("ablation.json"):
        return
    d = load("ablation.json")
    runs, variants = d["raw"], d["meta"]["variants"]
    idx = defaultdict(dict)
    for r in runs:
        idx[(r["family"], r["seed"])][r["variant"]] = r
    keys = sorted(idx)
    labels = {"full": "Full CC-LNS", "generic_destroy": "Generic destroy operators",
              "no_lexicographic": "Non-lexicographic incumbent", "no_surrogate": "No FFF surrogate",
              "no_polish": "No 2-opt polish", "constant_penalty": "Constant penalty",
              "cost_only_repair": "Modal-cost-only repair", "no_annealing": "No annealing",
              "random_positions": "Eight sampled positions per cell",
              "two_positions": "Two cheapest positions per cell",
              "no_random_removal": "No random removal"}
    pvals, info = [], {}
    for v in variants[1:]:
        b = sum(idx[k]["full"]["ceiling_met"] and not idx[k][v]["ceiling_met"] for k in keys)
        c = sum(idx[k][v]["ceiling_met"] and not idx[k]["full"]["ceiling_met"] for k in keys)
        p = mcnemar_p(b, c)
        info[v] = dict(b=b, c=c, p=p)
        pvals.append(p)
    for v, ph in zip(variants[1:], holm(pvals)):
        info[v]["p_holm"] = ph
    rows = []
    for v in variants:
        rr = [idx[k][v] for k in keys]
        met = sum(r["ceiling_met"] for r in rr)
        exc = st.mean(max(0.0, r["max_risk"] - r["r_bar"]) for r in rr)
        w = st.mean(100.0 * (idx[k][v]["makespan"] / idx[k]["full"]["makespan"] - 1.0) for k in keys)
        ptxt = "--" if v == "full" else fmt_p(info[v]["p_holm"])
        rows.append(f"{labels.get(v, v)} & {met}/{len(rr)} & {exc:.3f} & ${w:+.2f}$ & {ptxt}\\\\")
        info.setdefault(v, {}).update(met=met, runs=len(rr), excess=exc, workload_pct=w)
    write("tab_ablation.tex", f"""\\begin{{table}}[tb]
\\centering
\\caption{{Component ablation of CC-LNS at $\\bar r=0.30$ on C2, C4 and F2
(ten seeds each). Met: ceiling-satisfying plans; workload relative to the full
method on the same instances; $p$: exact McNemar test on paired attainment
against the full method, Holm-adjusted over the {len(variants) - 1} variants.}}
\\label{{tab:ablation}}
\\footnotesize
\\setlength{{\\tabcolsep}}{{3pt}}
\\begin{{tabular}}{{@{{}}lrrrr@{{}}}}
\\toprule
Variant & Met & Excess & Workload (\\%) & $p$\\\\\\midrule
""" + "\n".join(rows) + """
\\bottomrule
\\end{tabular}
\\end{table}
""")
    for v in variants:
        num(f"abl.met.{v}", info[v]["met"])
        num(f"abl.wl.{v}", f"${info[v]['workload_pct']:+.1f}$")
        if v != "full":
            num(f"abl.p.{v}", fmt_p(info[v]["p_holm"]))
    num("abl.runs", info["full"]["runs"])
    words = {7: "seven", 8: "eight", 9: "nine", 10: "ten", 11: "eleven", 12: "twelve"}
    num("abl.nvariants", words.get(len(variants) - 1, str(len(variants) - 1)))
    SUMMARY["ablation"] = info
    print("  ablation:", {v: info[v].get("met") for v in variants})


