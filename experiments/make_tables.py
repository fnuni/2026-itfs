def assignment_balance():
    """Route-to-vehicle assignment on the returned fleet plans (release 9).

    The cell FFF, the workload and every cell risk are invariant to the
    assignment of routes to vehicles; the row-wise average of release 8 is
    not.  For the CC-LNS fleet plans of the ceiling study (F2) and the
    public-data replay plans, compare the balanced assignment (lexicographic
    min-max of vehicle risk totals) with the block assignment that minimises
    the row-wise average.
    """
    from aggregators import (OWAFairness, RowOWAFairness, balanced_assignment,
                             block_assignment, vehicle_totals)
    mats = []
    if (RESULTS / "ceiling.json").exists():
        mats += [r["R"] for r in load("ceiling.json")["raw"]
                 if r["family"] == "F2" and r["method"] == "CC-LNS"]
    if (RESULTS / "external_v4.json").exists():
        mats += [r["R"] for r in load("external_v4.json")["raw"] if r.get("R")]
    if not mats:
        return
    row_gain, top_inc, fff_same = [], [], 0
    for R in mats:
        bal, blk = balanced_assignment(R), block_assignment(R)
        fff_same += abs(OWAFairness()(bal) - OWAFairness()(blk)) < 1e-12
        rb, rk = RowOWAFairness()(bal), RowOWAFairness()(blk)
        if rb > 1e-12:
            row_gain.append(100.0 * (1.0 - rk / rb))
        tb, tk = vehicle_totals(bal)[0], vehicle_totals(blk)[0]
        if tb > 1e-12:
            top_inc.append(100.0 * (tk / tb - 1.0))
    num("assign.plans", len(mats))
    num("assign.fffsame", fff_same)
    num("assign.rowgain", f"{st.median(row_gain):.1f}")
    num("assign.topinc", f"{st.median(top_inc):.0f}")
    num("assign.topinc.max", f"{max(top_inc):.0f}")
    SUMMARY["assignment"] = dict(plans=len(mats), fff_invariant=fff_same,
                                 row_average_gain_of_block_median_pct=st.median(row_gain),
                                 top_vehicle_total_increase_median_pct=st.median(top_inc))
    print("  assignment:", SUMMARY["assignment"])


