def certificates(R):
    """Worst-cell certificates of the cell-anonymous FFF (release 9).

    With n = KP cells and the arithmetic profile, M <= (n+1) FFF / 2 (global)
    and M <= (n+1) FFF - sum(R) (refined, finite Chebyshev inequality).
    """
    f = sorted((v for row in R for v in row), reverse=True)
    n = len(f)
    w = [2.0 * (n - j) / (n * (n + 1)) for j in range(n)]
    s = sum(wi * ri for wi, ri in zip(w, f))
    t = sum(f)
    g = min(1.0, (n + 1) * s / 2.0)
    r = min(1.0, max(0.0, (n + 1) * s - t))
    return g, r


