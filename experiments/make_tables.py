def write_numbers():
    lines = ["% Generated by experiments/make_tables.py; do not edit.",
             "\\makeatletter",
             "\\providecommand{\\res}[1]{\\@ifundefined{res@#1}{\\textbf{??}}"
             "{\\csname res@#1\\endcsname}}"]
