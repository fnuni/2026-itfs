def exact_tables():
    if not exists("exact_small.json"):
        return
    recs = load("exact_small.json")["raw"]
    methods = common.METHODS + ["OR-Tools", "HGS"]
    methods = [m for m in methods if any(r["method"] == m for r in recs[0]["runs"])]
    pairs = [(rec, c) for rec in recs for c in common.CEILINGS]
    att = [(rec, c) for rec, c in pairs if rec["exact"][str(c)]["attainable"]]
    unknown = [(rec, c) for rec, c in pairs if rec["exact"][str(c)]["attainable"] is None]
    rows, summ = [], {}
    for m in methods:
        met = gaps = 0
        gl, opt = [], 0
        false_success = 0
        for rec, c in pairs:
            run = next(r for r in rec["runs"] if r["method"] == m and r["r_bar"] == c)
            ex = rec["exact"][str(c)]
            if run["ceiling_met"] and not ex["attainable"]:
                false_success += 1
            if ex["attainable"] and run["ceiling_met"]:
                met += 1
                g = 100.0 * (run["makespan"] / ex["workload"] - 1.0)
                gl.append(g)
                opt += g < 1e-6
        summ[m] = dict(met=met, attainable=len(att), mean_gap=st.mean(gl) if gl else None,
                       median_gap=st.median(gl) if gl else None,
                       max_gap=max(gl) if gl else None, optimal=opt,
                       false_success=false_success)
        name = f"\\textbf{{{m}}}" if m == "CC-LNS" else (m + "$^\\ast$" if m in ("OR-Tools", "HGS") else m)
        rule = "\\midrule\n" if m == "OR-Tools" else ""
        rows.append(f"{rule}{name} & {met}/{len(att)} & {pct(met, len(att)):.1f} & "
                    f"{(st.mean(gl) if gl else float('nan')):.2f} & "
                    f"{(max(gl) if gl else float('nan')):.2f} & {opt}\\\\")
    fam_rows = []
    for f in common.SMALL_FAMILIES:
        rr = [rec for rec in recs if rec["family"] == f]
        if not rr:
            continue
        a = sum(rec["exact"][str(c)]["attainable"] is True for rec in rr for c in common.CEILINGS)
        rmins = [rec["r_min"] for rec in rr if rec["r_min"] is not None]
        cc = sum(next(r for r in rec["runs"] if r["method"] == "CC-LNS" and r["r_bar"] == c)["ceiling_met"]
                 for rec in rr for c in common.CEILINGS if rec["exact"][str(c)]["attainable"])
        n0, K, P = rr[0]["n"], rr[0]["K"], rr[0]["P"]
        fam_rows.append(f"{f} & {n0} & {K} & {P} & {a}/{4 * len(rr)} & "
                        f"{st.median(rmins):.3f} & {cc}/{a}\\\\")
    write("tab_exact.tex", f"""\\begin{{table}}[tb]
\\centering
\\caption{{Certified small-instance study ({len(recs)} instances, {len(pairs)}
instance--ceiling pairs, {len(att)} certified attainable; families in
Table~\\ref{{tab:cases}}). Met counts ceiling-satisfying plans among the
attainable pairs; gaps are relative to the certified minimum workload over
successful runs; Opt.\\ counts runs that reach the optimum. No method can meet
an unattainable ceiling, and none did. $^\\ast$Routing engine on the crisp
equivalent, {load('exact_small.json')['meta']['ortools_seconds']:.0f}\\,s.}}
\\label{{tab:exact}}
\\footnotesize
\\setlength{{\\tabcolsep}}{{3pt}}
\\begin{{tabular}}{{@{{}}lrrrrr@{{}}}}
\\toprule
Method & Met & \\% & Mean gap (\\%) & Max gap (\\%) & Opt.\\\\\\midrule
""" + "\n".join(rows) + """
\\bottomrule
\\end{tabular}
\\end{table}
""")
    write("tab_exact_family.tex", """\\begin{table}[tb]
\\centering
\\caption{Small families: certified attainable instance--ceiling pairs, median
exact minimum worst-cell credibility $r_{\\min}$, and CC-LNS successes among
attainable pairs.}
\\label{tab:exact-family}
\\footnotesize
\\setlength{\\tabcolsep}{3pt}
\\begin{tabular}{@{}lrrrrrr@{}}
\\toprule
Family & $n$ & $K$ & $P$ & Attainable & $r_{\\min}$ & CC-LNS\\\\\\midrule
""" + "\n".join(fam_rows) + """
\\bottomrule
\\end{tabular}
\\end{table}
""")
    unatt = sum(1 for rec, c in pairs if rec["exact"][str(c)]["attainable"] is False)
    num("exact.instances", len(recs))
    num("exact.pairs", len(pairs))
    num("exact.attainable", len(att))
    num("exact.unattainable", unatt)
    num("exact.unknown", len(unknown))
    num("exact.seconds", f"{st.median(r['exact_seconds'] for r in recs):.1f}")
    num("exact.seconds.max", f"{max(r['exact_seconds'] for r in recs):.1f}")
    for m in methods:
        v = summ[m]
        num(f"exact.met.{m}", v["met"])
        num(f"exact.pct.{m}", f"{pct(v['met'], len(att)):.1f}")
        num(f"exact.gap.{m}", f"{v['mean_gap']:.2f}" if v["mean_gap"] is not None else "--")
        num(f"exact.maxgap.{m}", f"{v['max_gap']:.2f}" if v["max_gap"] is not None else "--")
        num(f"exact.opt.{m}", v["optimal"])
        num(f"exact.false.{m}", v["false_success"])
    SUMMARY["exact"] = dict(by_method=summ, pairs=len(pairs), attainable=len(att),
                            unknown=len(unknown), instances=len(recs),
                            exact_seconds_median=st.median(r["exact_seconds"] for r in recs))
    print("  exact:", {m: f"{v['met']}/{v['attainable']} gap {v['mean_gap']}" for m, v in summ.items()})


