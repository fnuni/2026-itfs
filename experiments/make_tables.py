def sweep_table(name, label, caption, group="method", order=None):
    if not exists(f"{name}.json"):
        return
    runs = load(f"{name}.json")["raw"]
    fams = sorted({r["family"] for r in runs})
    keyf = (lambda r: r["method"]) if group == "method" else (lambda r: r["aggregator"])
    groups = order or sorted({keyf(r) for r in runs})
    ref = groups[0]
    rows, info = [], {}
    pv = []
    for gname in groups:
        rr = [r for r in runs if keyf(r) == gname]
        med = lambda k: st.median(r[k] for r in rr)
        info[gname] = dict(max_risk=med("max_risk"), makespan=med("makespan"), fff=med("fff"),
                           gini=med("gini"), hv=med("hv"), n=len(rr))
    for gname in groups[1:]:
        diffs = []
        for f in fams:
            for s in common.SEEDS5:
                a = [r for r in runs if keyf(r) == ref and r["family"] == f and r["seed"] == s]
                b = [r for r in runs if keyf(r) == gname and r["family"] == f and r["seed"] == s]
                if a and b:
                    diffs.append(b[0]["max_risk"] - a[0]["max_risk"])
        info[gname]["p_maxrisk"] = sign_test_p(diffs)
        pv.append(info[gname]["p_maxrisk"])
    for gname, ph in zip(groups[1:], holm(pv)):
        info[gname]["p_maxrisk_holm"] = ph
    for gname in groups:
        i = info[gname]
        ptxt = "--" if gname == ref else fmt_p(i["p_maxrisk_holm"])
        rows.append(f"{gname} & {i['max_risk']:.3f} & {i['fff']:.3f} & {i['gini']:.3f} & "
                    f"{i['makespan']:.1f} & {i['hv']:.3f} & {ptxt}\\\\")
    write(f"tab_{name}.tex", f"""\\begin{{table}}[tb]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\scriptsize
\\setlength{{\\tabcolsep}}{{2.6pt}}
\\begin{{tabular}}{{@{{}}lrrrrrr@{{}}}}
\\toprule
{'Method' if group == 'method' else 'Aggregator'} & Max risk & FFF & Gini & Workload & HV & $p$\\\\\\midrule
""" + "\n".join(rows) + """
\\bottomrule
\\end{tabular}
\\end{table}
""")
    for gname in groups:
        i = info[gname]
        num(f"{name}.maxrisk.{gname}", f"{i['max_risk']:.3f}")
        num(f"{name}.fff.{gname}", f"{i['fff']:.3f}")
        num(f"{name}.wl.{gname}", f"{i['makespan']:.1f}")
        num(f"{name}.hv.{gname}", f"{i['hv']:.3f}")
        if gname != ref:
            num(f"{name}.p.{gname}", fmt_p(i["p_maxrisk_holm"]))
    alt = groups[1:]
    if name == "aggregators":
        ca = [g for g in alt if g != "Mean"]
        num("aggregators.maxrisk.ca.min", f"{min(info[g]['max_risk'] for g in ca):.3f}")
        num("aggregators.maxrisk.ca.max", f"{max(info[g]['max_risk'] for g in ca):.3f}")
        num("aggregators.pmin.ca", fmt_p(min(info[g]["p_maxrisk_holm"] for g in ca)))
        num("aggregators.wlrel.ca.max",
            f"{max(100.0 * (info[g]['makespan'] / info[ref]['makespan'] - 1.0) for g in ca):.1f}")
    for g in alt:
        num(f"{name}.wlrel.{g}", f"{100.0 * (info[ref]['makespan'] / info[g]['makespan'] - 1.0):.1f}")
    num(f"{name}.maxrisk.alt.min", f"{min(info[g]['max_risk'] for g in alt):.3f}")
    num(f"{name}.maxrisk.alt.max", f"{max(info[g]['max_risk'] for g in alt):.3f}")
    num(f"{name}.hv.alt.max", f"{max(info[g]['hv'] for g in alt):.3f}")
    num(f"{name}.wl.alt.min", f"{min(info[g]['makespan'] for g in alt):.1f}")
    num(f"{name}.pmax", ("$p<0.001$" if max(info[g]["p_maxrisk_holm"] for g in alt) < 0.001
                         else f"$p\\le{max(info[g]['p_maxrisk_holm'] for g in alt):.3f}$"))
    SUMMARY[name] = info
    print(f"  {name}:", {g: round(info[g]['max_risk'], 3) for g in groups})


