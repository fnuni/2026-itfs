"""Tables and quoted numbers of the extended Amazon replay.

    python3 experiments/summarize_external_extended.py

Reads results/external_extended_{equal,long,shapes,iterations}.json and writes
tables/tab_external_extended.tex (main), tables/tab_external_extended_alpha.tex
(supplement) and tables/numbers_external_extended.tex (\\res{ext.*}).
Comparisons are paired on (route, alpha) blocks within one block of runs on
one machine; repetitions are averaged within a route before comparison.
"""
from __future__ import annotations

import json
import statistics as st
from abc import ABC
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES, TAB = ROOT / "results", ROOT / "tables"
HEADER = "% Generated by experiments/summarize_external_extended.py; do not edit.\n"
METHODS = ("OR-dense", "OR-adaptive", "CC-full", "CC-modal", "OR+CC")
LABEL = {"OR-dense": "OR-dense (12)", "OR-adaptive": "OR-adaptive", "CC-full": "CC-full",
         "CC-modal": "CC-modal", "OR+CC": "OR+CC"}
ALPHAS = (0.1, 0.3, 0.7)


class Block:
    """Runs of one block and one membership scenario."""

    def __init__(self, label, rows):
        self.label, self.rows = label, rows
        self.by = defaultdict(list)
        for r in rows:
            self.by[r["instance"], r["alpha"], r["method"]].append(r)
        self.routes = sorted({r["instance"] for r in rows})

    def mean_J(self, inst, alpha, method):
        js = [r["J"] for r in self.by[inst, alpha, method] if r.get("J") is not None]
        return st.mean(js) if js else None

    def deltas(self, method, alphas=ALPHAS):
        out = []
        for a in alphas:
            for i in self.routes:
                b, c = self.mean_J(i, a, "OR-sweep"), self.mean_J(i, a, method)
                if b is not None and c is not None:
                    out.append(100 * (c - b) / b)
        return out

    def feasible(self, method):
        rs = [r for r in self.rows if r["method"] == method]
        return sum(bool(r.get("feasible")) for r in rs), len(rs)

    def median(self, method, key):
        v = [r[key] for r in self.rows if r["method"] == method and r.get(key) is not None]
        return st.median(v) if v else None

    def max_risk_delta(self, method, alpha):
        out = []
        for i in self.routes:
            b = [r["max_risk"] for r in self.by[i, alpha, "OR-sweep"] if r.get("max_risk") is not None]
            c = [r["max_risk"] for r in self.by[i, alpha, method] if r.get("max_risk") is not None]
            if b and c:
                out.append(st.mean(c) - st.mean(b))
        return st.mean(out) if out else None


def load_blocks():
    blocks = []
    for name, label in (("equal", "4\\,s"), ("long", "16\\,s")):
        p = RES / f"external_extended_{name}.json"
        if p.exists():
            blocks.append((name, Block(label, json.loads(p.read_text())["raw"])))
    p = RES / "external_extended_shapes.json"
    if p.exists():
        raw = json.loads(p.read_text())["raw"]
        for sc, label in (("symmetric", "Sym."), ("elicited", "Elicit. med."), ("random", "Rand.")):
            rows = [r for r in raw if r["scenario"] == sc]
            if rows:
                blocks.append((sc, Block(label, rows)))
    return blocks


class Writer(ABC):
    def __init__(self, blocks):
        self.blocks = blocks

    @staticmethod
    def fmt(v):
        s = f"{v:.1f}"
        return f"$-${s[1:]}" if s.startswith("-") else s


class MainTable(Writer):
    def write(self):
        heads = " & ".join(b.label for _, b in self.blocks)
        rows = []
        for m in METHODS:
            cells = []
            for _, b in self.blocks:
                d = b.deltas(m)
                cells.append(f"{self.fmt(st.mean(d))} ({sum(x < -1e-9 for x in d)})" if d else "--")
            rows.append(f"{LABEL[m]} & " + " & ".join(cells) + "\\\\")
        n = len(self.blocks[0][1].routes) * len(ALPHAS)
        text = (HEADER + "\\begin{table}[tb]\n\\centering\n"
                "\\caption{Extended replay on the eight Amazon routes, methods compared within each "
                "scenario execution, all on one host: mean change of the route-level mean $J_\\alpha$ relative to "
                f"the four-ceiling OR-sweep (\\%), over three $\\alpha$, with the number of the {n} "
                "route--$\\alpha$ blocks improved in parentheses. Columns: published memberships at "
                "4\\,s (three repetitions) and 16\\,s, and, at 4\\,s, symmetric 25/20\\%, R1 expert median "
                "and seeded random spreads.}\n\\label{tab:external-extended}\n\\scriptsize\n"
                "\\setlength{\\tabcolsep}{2.2pt}\n\\begin{tabular}{@{}l" + "c" * len(self.blocks) +
                "@{}}\n\\toprule\nMethod & " + heads + "\\\\\\midrule\n" + "\n".join(rows) +
                "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
        (TAB / "tab_external_extended.tex").write_text(text)


class AlphaTable(Writer):
    def write(self):
        rows = []
        for name, b in self.blocks:
            for m in METHODS:
                cells = []
                for a in ALPHAS:
                    d = b.deltas(m, (a,))
                    cells.append(f"{self.fmt(st.mean(d))} ({sum(x < -1e-9 for x in d)})" if d else "--")
                f, t = b.feasible(m)
                rows.append(f"{b.label} & {LABEL[m]} & " + " & ".join(cells) + f" & {f}/{t}\\\\")
            rows.append("\\midrule")
        rows = rows[:-1]
        text = (HEADER + "\\begin{table}[tb]\n\\centering\n"
                "\\caption{Extended replay by preference: mean change of route-level mean $J_\\alpha$ "
                "relative to the four-ceiling OR-sweep of the same block (\\%; routes improved of "
                "eight) and feasible plans.}\n\\label{tab:external-extended-alpha}\n\\scriptsize\n"
                "\\setlength{\\tabcolsep}{2.4pt}\n\\begin{tabular}{@{}llcccc@{}}\n\\toprule\n"
                "Block & Method & $\\alpha=0.1$ & $0.3$ & $0.7$ & Feas.\\\\\\midrule\n" +
                "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
        (TAB / "tab_external_extended_alpha.tex").write_text(text)


class Numbers(Writer):
    def write(self):
        d = dict(IterationMatched().numbers())
        B = dict(self.blocks)

        def put(k, v):
            d[k] = v if isinstance(v, str) else (f"{v:.1f}" if isinstance(v, float) else str(v))
        for name, b in self.blocks:
            for m in METHODS:
                key = m.replace("+", "").replace("-", "").lower()
                dl = b.deltas(m)
                if dl:
                    put(f"ext.{name}.{key}", st.mean(dl))
                    put(f"ext.{name}.{key}.wins", sum(x < -1e-9 for x in dl))
            put(f"ext.{name}.blocks", len(b.routes) * len(ALPHAS))
            put(f"ext.{name}.runs", len(b.rows))
            f = sum(bool(r.get("feasible")) for r in b.rows)
            put(f"ext.{name}.feasible", f)
            for m in ("CC-full", "CC-modal"):
                key = m.replace("-", "").lower()
                it = b.median(m, "iterations")
                if it is not None:
                    put(f"ext.{name}.{key}.iter", f"{it:.0f}")
                c = b.median(m, "endpoint_candidates")
                if c is not None and it:
                    put(f"ext.{name}.{key}.cand", f"{c / max(it, 1):.0f}")
        for name in B:
            b = B[name]
            for m in ("OR+CC", "CC-modal"):
                key = m.replace("+", "").replace("-", "").lower()
                v = b.max_risk_delta(m, 0.3)
                if v is not None:
                    put(f"ext.{name}.{key}.dmaxrisk", f"{v:+.3f}")
        for name, b in self.blocks:
            f, m = b.deltas("CC-full"), b.deltas("CC-modal")
            if f and m:
                put(f"ext.{name}.gap", st.mean(f) - st.mean(m))
        for m in ("OR+CC", "CC-modal"):
            key = m.replace("+", "").replace("-", "").lower()
            vals = [B[n].max_risk_delta(m, 0.3) for n in B]
            vals = [v for v in vals if v is not None]
            if vals:
                put(f"ext.all.{key}.dmaxrisk.min", f"{min(vals):+.3f}")
                put(f"ext.all.{key}.dmaxrisk.max", f"{max(vals):+.3f}")
        if "equal" in B:
            ratio = B["equal"].median("CC-modal", "iterations") / max(1, B["equal"].median("CC-full", "iterations"))
            put("ext.equal.iterratio", f"{ratio:.1f}")
        if "long" in B:
            ratio = B["long"].median("CC-modal", "iterations") / max(1, B["long"].median("CC-full", "iterations"))
            put("ext.long.iterratio", f"{ratio:.1f}")
        shapes = [n for n in ("symmetric", "elicited", "random") if n in B]
        for m in METHODS:
            key = m.replace("+", "").replace("-", "").lower()
            vals = [st.mean(B[n].deltas(m)) for n in shapes if B[n].deltas(m)]
            if vals:
                put(f"ext.shapes.{key}.min", min(vals))
                put(f"ext.shapes.{key}.max", max(vals))
        lines = [HEADER.strip(), "\\makeatletter",
                 "\\providecommand{\\res}[1]{\\@ifundefined{res@#1}{\\textbf{??}}{\\csname res@#1\\endcsname}}"]
        for k in sorted(d):
            v = d[k]
            if v.startswith("-"):
                v = "$-$" + v[1:]
            lines.append(f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}")
        lines.append("\\makeatother")
        (TAB / "numbers_external_extended.tex").write_text("\n".join(lines) + "\n")
        return d


class IterationMatched:
    """CC-modal against CC-full with the same number of iterations (route-level means)."""

    def __init__(self):
        p = RES / "external_extended_iterations.json"
        self.rows = json.loads(p.read_text())["raw"] if p.exists() else []

    def numbers(self):
        if not self.rows:
            return {}
        b = Block("iter", self.rows)
        d = []
        for a in ALPHAS:
            for i in b.routes:
                f, m = b.mean_J(i, a, "CC-full"), b.mean_J(i, a, "CC-modal")
                if f is not None and m is not None:
                    d.append(100 * (m - f) / f)
        sec = {m: st.median(r["wall_clock_s"] for r in self.rows if r["method"] == m)
               for m in ("CC-full", "CC-modal")}
        return {"ext.iter.budget": str(self.rows[0]["iteration_budget"]),
                "ext.iter.modalvsfull": f"{st.mean(d):+.1f}",
                "ext.iter.fullwins": str(sum(x > 1e-9 for x in d)),
                "ext.iter.blocks": str(len(d)),
                "ext.iter.full.s": f"{sec['CC-full']:.1f}",
                "ext.iter.modal.s": f"{sec['CC-modal']:.1f}"}


def main():
    blocks = load_blocks()
    if not blocks:
        print("no extended records")
        return
    MainTable(blocks).write()
    AlphaTable(blocks).write()
    d = Numbers(blocks).write()
    for k in sorted(d):
        print(k, d[k])


if __name__ == "__main__":
    main()
